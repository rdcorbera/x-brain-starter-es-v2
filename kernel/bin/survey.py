#!/usr/bin/env python3
"""Read-only survey of an X-Brain knowledge bundle.

Measures where tokens go as a brain grows. Reports shapes and counts only --
never document content -- so the output is safe to share from a restricted
environment.

Stdlib only. No writes. No network. Python 3.9+ -- deliberately lower than
brain.py's 3.11 floor. This is the preflight: it runs on the target machine
BEFORE anything is installed, to find out what is there. A preflight that
depends on its own findings is no preflight.

Usage:
    python3 kernel/bin/survey.py [BUNDLE] [--touched N] [--json]

    BUNDLE      Path to the knowledge bundle (default: ./cerebro)
    --touched   Indexes assumed touched per ingest, for the cost estimate
                (default: 4)
    --json      Emit machine-readable output instead of the report
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path
from typing import Dict, List, Optional, Tuple

# --- Constants ---------------------------------------------------------------

SKIP_DIRS = {".git", ".venv", "venv", "node_modules", "__pycache__", ".obsidian"}

# Files that are reserved by OKF and carry no typed frontmatter.
RESERVED = {"index.md", "log.md"}

# Derived artifacts: regenerated by the model today, and growing with the brain.
DERIVED = {
    "PREGUNTAS-ABIERTAS.md": "preguntas abiertas",
    "ORGANIGRAMA.md": "organigrama",
}

# Fallback catalog: the 11 types of v1. Used only when no contract is present,
# which is the case that matters -- this script is meant to run against the v1
# brain in production, where kernel/schema/contract.json does not exist.
FALLBACK_TYPES = {
    "Iniciativa", "Insumo", "Reunion", "Decision", "Pregunta", "Persona",
    "Sistema", "Lineamiento", "Diagrama", "Playbook", "Glosario",
}


def load_catalog(contract_path: Path) -> Tuple[set, Dict[str, str], set, bool]:
    """Read types, derived files and reserved names from the contract.

    Hardcoding them was the same defect this whole redesign has been removing:
    the contract declares them, the code repeated them, and survey already
    disagreed -- it did not know about `Indice`.
    """
    try:
        data = json.loads(contract_path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return FALLBACK_TYPES, dict(DERIVED), set(RESERVED), False
    types = set(data.get("types", {})) or FALLBACK_TYPES
    # Deferred entries are counted on purpose: a v1 1.4.0 brain already has
    # PENDIENTES.md, written by hand, and its size is part of Slope A whether
    # or not our generator can produce it yet.
    derived = {k.split("/")[-1]: k for k in data.get("derived_files", {}) if k != "note"}
    reserved = {k for k in data.get("reserved_files", {}) if k != "note"} or set(RESERVED)
    return types, derived or dict(DERIVED), reserved, True

# Characters per token. Spanish prose runs ~3.5-4 with common tokenizers;
# 4 keeps the estimate conservative (i.e. it under-reports the problem).
CHARS_PER_TOKEN = 4

FM_DELIM = re.compile(r"^---\s*$")
FM_KEY = re.compile(r"^([A-Za-z_][A-Za-z0-9_.\-]*)\s*:")
MD_LINK = re.compile(r"\[[^\]]*\]\(([^)\s]+)\)")


def tokens(chars: int) -> int:
    return chars // CHARS_PER_TOKEN


# --- Scanning ----------------------------------------------------------------


class Doc:
    """One markdown file, reduced to the shape we measure."""

    __slots__ = ("path", "rel", "chars", "lines", "has_fm", "type", "keys", "links")

    def __init__(self, path: Path, rel: str) -> None:
        self.path = path
        self.rel = rel
        self.chars = 0
        self.lines = 0
        self.has_fm = False
        self.type: Optional[str] = None
        self.keys: List[str] = []
        self.links: List[str] = []


def scan_frontmatter(lines: List[str]) -> Tuple[bool, Optional[str], List[str]]:
    """Tolerantly extract top-level keys and `type` from a frontmatter block.

    Deliberately permissive: this runs over a corpus that may not conform, and
    must never fail. Strict parsing belongs in the validator, not here.
    """
    if not lines or not FM_DELIM.match(lines[0]):
        return False, None, []

    keys: List[str] = []
    doc_type: Optional[str] = None
    for line in lines[1:]:
        if FM_DELIM.match(line):
            return True, doc_type, keys
        if line.startswith((" ", "\t", "-")):
            continue  # nested value or list item; only top-level keys count
        match = FM_KEY.match(line)
        if not match:
            continue
        key = match.group(1)
        keys.append(key)
        if key == "type":
            value = line.split(":", 1)[1].strip().strip("\"'")
            doc_type = value or None
    return False, doc_type, keys  # unterminated block


def scan(bundle: Path, reserved: set) -> List[Doc]:
    docs: List[Doc] = []
    for root, dirnames, filenames in os.walk(bundle):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for name in filenames:
            if not name.endswith(".md"):
                continue
            path = Path(root) / name
            try:
                text = path.read_text(encoding="utf-8", errors="replace")
            except OSError as exc:
                print(f"warning: cannot read {path}: {exc}", file=sys.stderr)
                continue
            doc = Doc(path, str(path.relative_to(bundle)))
            doc.chars = len(text)
            lines = text.splitlines()
            doc.lines = len(lines)
            doc.has_fm, doc.type, doc.keys = scan_frontmatter(lines)
            doc.links = MD_LINK.findall(text)
            docs.append(doc)
    return docs


# --- Link resolution ---------------------------------------------------------


def classify_links(docs: List[Doc], bundle: Path) -> Dict[str, int]:
    """Resolve internal links. `/raw/...` points outside the bundle by design."""
    counts = Counter()
    for doc in docs:
        for target in doc.links:
            if target.startswith(("http://", "https://", "mailto:", "#")):
                counts["external"] += 1
            elif target.startswith("/raw/"):
                counts["raw_pointer"] += 1
            elif target.startswith("/"):
                counts["bundle"] += 1
                resolved = bundle / target.lstrip("/")
                counts["bundle_resolved" if resolved.exists() else "bundle_missing"] += 1
            else:
                counts["relative"] += 1
                resolved = (doc.path.parent / target).resolve()
                counts["relative_resolved" if resolved.exists() else "relative_missing"] += 1
    return dict(counts)


# --- Measurement -------------------------------------------------------------


def measure(bundle: Path, touched: int, contract_path: Path) -> dict:
    base_types, derived_files, reserved, from_contract = load_catalog(contract_path)
    docs = scan(bundle, reserved)
    if not docs:
        raise SystemExit(f"error: no .md files found under {bundle}")

    indexes = [d for d in docs if d.path.name == "index.md"]
    knowledge = [d for d in docs if d.path.name not in reserved]

    derived: Dict[str, dict] = {}
    for filename in derived_files:
        match = next((d for d in docs if d.path.name == filename), None)
        derived[filename] = {
            "found": match is not None,
            "lines": match.lines if match else 0,
            "tokens": tokens(match.chars) if match else 0,
        }

    index_tokens = [tokens(d.chars) for d in indexes]
    avg_index = sum(index_tokens) // len(index_tokens) if index_tokens else 0

    # Slope A: what the model reads AND rewrites to regenerate derived
    # artifacts during one ingest. Read + write, hence the doubling.
    derived_cost = sum(v["tokens"] for v in derived.values()) * 2
    index_cost = avg_index * touched * 2

    # Slope B: what a QUERY reads to find candidates by navigating indexes --
    # the root index plus one per level down, then opening the best matches.
    # Estimated so the A-versus-B call is MEASURED instead of inferred, which
    # is the decision this whole script exists to inform.
    root_index = next((tokens(d.chars) for d in indexes
                       if str(Path(d.rel).parent) == "."), 0)
    depth = max((len(Path(d.rel).parts) - 1 for d in knowledge), default=1)
    navigation = root_index + avg_index * max(depth - 1, 1)
    open_docs = sum(sorted((tokens(d.chars) for d in knowledge), reverse=True)[:5])

    directories = defaultdict(int)
    for doc in docs:
        directories[str(Path(doc.rel).parent)] += 1

    dirs_with_knowledge = {
        str(Path(d.rel).parent) for d in knowledge
    }
    dirs_with_index = {str(Path(d.rel).parent) for d in indexes}

    return {
        "bundle": str(bundle),
        "catalog_source": "contract" if from_contract else "fallback (sin contract.json)",
        "totals": {
            "md_files": len(docs),
            "knowledge_files": len(knowledge),
            "index_files": len(indexes),
            "directories": len(directories),
            "chars": sum(d.chars for d in docs),
            "tokens": tokens(sum(d.chars for d in docs)),
        },
        "slope_a": {
            "derived": derived,
            "index_count": len(indexes),
            "index_tokens_avg": avg_index,
            "index_tokens_max": max(index_tokens) if index_tokens else 0,
            "index_tokens_total": sum(index_tokens),
            "touched_assumption": touched,
            "derived_cost_per_ingest": derived_cost,
            "index_cost_per_ingest": index_cost,
            "total_cost_per_ingest": derived_cost + index_cost,
        },
        "slope_b": {
            "root_index_tokens": root_index,
            "max_depth": depth,
            "navigation_cost": navigation,
            "top5_docs_tokens": open_docs,
            "total_cost_per_query": navigation + open_docs,
        },
        "types": {
            "counts": dict(Counter(d.type for d in knowledge if d.type).most_common()),
            "untyped": sum(1 for d in knowledge if not d.type),
            "off_catalog": sorted(
                {d.type for d in knowledge if d.type and d.type not in base_types}
            ),
            "known": sorted(base_types),
        },
        "frontmatter": {
            "with_block": sum(1 for d in knowledge if d.has_fm),
            "without_block": sum(1 for d in knowledge if not d.has_fm),
            "field_frequency": dict(
                Counter(k for d in knowledge for k in set(d.keys)).most_common()
            ),
        },
        "indexes": {
            "dirs_with_knowledge": len(dirs_with_knowledge),
            "dirs_with_index": len(dirs_with_index & dirs_with_knowledge),
            "dirs_missing_index": sorted(dirs_with_knowledge - dirs_with_index)[:20],
            "dirs_missing_index_count": len(dirs_with_knowledge - dirs_with_index),
        },
        "links": classify_links(docs, bundle),
    }


# --- Report ------------------------------------------------------------------


def bar(value: int, ceiling: int, width: int = 28) -> str:
    if ceiling <= 0:
        return ""
    filled = min(width, round(width * value / ceiling))
    return "#" * filled + "." * (width - filled)


def report(m: dict) -> None:
    t = m["totals"]
    a = m["slope_a"]
    out = print

    out()
    out("=" * 66)
    out(f"  X-BRAIN SURVEY  --  {m['bundle']}")
    out("=" * 66)

    out()
    out("CORPUS")
    out(f"  markdown files          {t['md_files']:>9,}")
    out(f"    knowledge             {t['knowledge_files']:>9,}")
    out(f"    index.md              {t['index_files']:>9,}")
    out(f"  directories             {t['directories']:>9,}")
    out(f"  estimated tokens        {t['tokens']:>9,}")
    out(f"  catálogo leído de       {m['catalog_source']:>9}")

    out()
    out("SLOPE A  --  derived artifacts rewritten by the model")
    out("  These grow with the brain and are regenerated by hand on each ingest.")
    out()
    for filename, d in a["derived"].items():
        if d["found"]:
            out(f"  {filename:<26} {d['lines']:>6,} lines   {d['tokens']:>8,} tokens")
        else:
            out(f"  {filename:<26} {'not found':>21}")
    out(f"  {'index.md (average)':<26} {'':>6}          {a['index_tokens_avg']:>8,} tokens")
    out(f"  {'index.md (largest)':<26} {'':>6}          {a['index_tokens_max']:>8,} tokens")

    out()
    out(f"  Cost per ingest (read + rewrite, {a['touched_assumption']} indexes touched):")
    out(f"    derived artifacts     {a['derived_cost_per_ingest']:>9,} tokens")
    out(f"    index.md files        {a['index_cost_per_ingest']:>9,} tokens")
    out(f"    {'TOTAL':<21} {a['total_cost_per_ingest']:>9,} tokens")

    total = a["total_cost_per_ingest"]
    out()
    out("  How to read this:")
    if total > 20000:
        out(f"    {total:,} tokens per ingest is mechanical rewriting that a")
        out("    deterministic generator takes to ZERO. Slope A is the dominant")
        out("    cost -- proceed with the plan as written.")
    elif total > 5000:
        out(f"    {total:,} tokens per ingest is worth removing, but check whether")
        out("    discovery (finding affected pages among N docs) costs more.")
        out("    If it does, pull the projection into cut 1.")
    else:
        out(f"    {total:,} tokens per ingest is marginal. The spend is likely in")
        out("    DISCOVERY, not regeneration -- compress the plan and bring the")
        out("    projection forward into cut 1.")

    b = m["slope_b"]
    out()
    out("SLOPE B  --  discovery: what a query reads to find candidates")
    out(f"  índice raíz             {b['root_index_tokens']:>9,} tokens")
    out(f"  profundidad máxima      {b['max_depth']:>9} niveles")
    out(f"  navegar índices         {b['navigation_cost']:>9,} tokens")
    out(f"  abrir los 5 mayores     {b['top5_docs_tokens']:>9,} tokens")
    out(f"  {'TOTAL por consulta':<23} {b['total_cost_per_query']:>9,} tokens")

    out()
    out("A CONTRA B  --  qué CRECE con el cerebro")
    out("  Solo se comparan las partes que crecen con N. Abrir los documentos")
    out("  encontrados cuesta lo mismo con 100 que con 100.000, así que queda fuera.")
    out()
    sa, sb = a["total_cost_per_ingest"], b["navigation_cost"]
    out(f"  A · regenerar derivados, por ingesta      {sa:>9,} tokens")
    out(f"  B · navegar índices, por consulta         {sb:>9,} tokens")
    out()
    if t["knowledge_files"] < 200:
        out(f"  AVISO: solo {t['knowledge_files']} documentos de conocimiento. Ninguna de las dos")
        out("  pendientes se ha manifestado todavía; este veredicto no es fiable")
        out("  por debajo de ~200. Córrelo sobre el cerebro real.")
    elif sa > sb * 2:
        out("  -> A domina. El corte 1 la elimina entera: el plan está bien ordenado.")
    elif sb > sa * 2:
        out("  -> B domina. COMPRIME EL PLAN: adelanta la proyección al corte 1.")
    else:
        out("  -> comparables. Mantén el orden, pero no difieras B más de un corte.")
    out()
    out("  Nota de unidades: A es por ingesta y B por consulta. Si consultas mucho")
    out("  más de lo que ingieres, pondera B en esa proporción antes de decidir.")

    out()
    out("TYPES")
    counts = m["types"]["counts"]
    if counts:
        ceiling = max(counts.values())
        for name, n in counts.items():
            flag = "" if name in m["types"]["known"] else "  <- off catalog"
            out(f"  {name:<18} {n:>7,}  {bar(n, ceiling)}{flag}")
    if m["types"]["untyped"]:
        out(f"  {'(no type field)':<18} {m['types']['untyped']:>7,}")
    if m["types"]["off_catalog"]:
        out(f"  off-catalog values: {', '.join(m['types']['off_catalog'])}")

    out()
    out("FRONTMATTER HEALTH")
    fm = m["frontmatter"]
    total_k = fm["with_block"] + fm["without_block"]
    pct = (100 * fm["with_block"] // total_k) if total_k else 0
    out(f"  with frontmatter        {fm['with_block']:>9,}  ({pct}%)")
    out(f"  without                 {fm['without_block']:>9,}")
    out("  field frequency (top 15):")
    for key, n in list(fm["field_frequency"].items())[:15]:
        out(f"    {key:<22} {n:>7,}")

    out()
    out("INDEX COVERAGE")
    ix = m["indexes"]
    pct = (100 * ix["dirs_with_index"] // ix["dirs_with_knowledge"]) if ix["dirs_with_knowledge"] else 0
    out(f"  dirs with knowledge     {ix['dirs_with_knowledge']:>9,}")
    out(f"  of those, with index.md {ix['dirs_with_index']:>9,}  ({pct}%)")
    out(f"  missing index.md        {ix['dirs_missing_index_count']:>9,}")
    for d in ix["dirs_missing_index"]:
        out(f"    {d}")
    if ix["dirs_missing_index_count"] > len(ix["dirs_missing_index"]):
        remaining = ix["dirs_missing_index_count"] - len(ix["dirs_missing_index"])
        out(f"    ... and {remaining:,} more")

    out()
    out("LINKS")
    for key in ("bundle", "bundle_resolved", "bundle_missing", "relative",
                "relative_resolved", "relative_missing", "raw_pointer", "external"):
        if key in m["links"]:
            out(f"  {key:<22} {m['links'][key]:>9,}")
    out("  (missing bundle links are tolerated by OKF: they mark knowledge")
    out("   not yet written, not errors)")

    out()
    out("=" * 66)
    out("  No document content was read out. Counts and shapes only.")
    out("=" * 66)
    out()


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Read-only survey of an X-Brain knowledge bundle."
    )
    parser.add_argument("bundle", nargs="?", default="cerebro",
                        help="path to the knowledge bundle (default: cerebro)")
    parser.add_argument("--touched", type=int, default=4,
                        help="index.md files assumed touched per ingest (default: 4)")
    parser.add_argument("--contract", default="kernel/schema/contract.json",
                        help="contract to read the catalog from; falls back to the "
                             "built-in v1 list when absent (a v1 brain has none)")
    parser.add_argument("--json", action="store_true",
                        help="emit machine-readable output")
    args = parser.parse_args()

    bundle = Path(args.bundle).expanduser()
    if not bundle.is_dir():
        print(f"error: {bundle} is not a directory", file=sys.stderr)
        return 2

    measurements = measure(bundle, args.touched, Path(args.contract))
    if args.json:
        print(json.dumps(measurements, indent=2, ensure_ascii=False))
    else:
        report(measurements)
    return 0


if __name__ == "__main__":
    sys.exit(main())
